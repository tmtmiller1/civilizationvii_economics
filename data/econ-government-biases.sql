-- Economics: one government bias for each civilization in its own age (DESIGN 4.17 and section 6; the table and the
-- reason for each pick are in docs/government-biases.md). Loaded with the Economic systems option on
-- (economics.modinfo, criteria systems-option-on), in every age's database. The game reads its AI lists when a game is
-- created, so the rows reach new games only.
--
-- Only GovernmentBiases rows are touched, never another system's rows on the same lists. Every statement selects
-- through Traits and Governments, so a civilization from a DLC that isn't owned, or a government that isn't in this
-- age's database or that an update renames, skips its row instead of stopping game creation.
--
-- A civilization the base game already gives a bias: its one GovernmentBiases item is rewritten in place, matched on
-- the base game's government. An UPDATE that names the old item leaves alone any row another mod added to the list,
-- and if a mod loaded before this one has already pointed the civilization elsewhere, the match finds nothing and that
-- mod's choice stands. A DELETE and INSERT would need the same narrow match, in two statements instead of one.
-- Heian's base row names GOVERNMENT_CLASSIC_REPUBLIC, which doesn't exist, so it matches either spelling.
--
-- A civilization with no GovernmentBiases list on its trait in this database gets one of its own, named
-- 'Economics <trait> Government Bias'. A list that another mod has already added is left as it is.
--
-- Every row is at 75: above the base game's 25 and 50 and above the 50 that moved the civilizations without a row of
-- their own in the macro probe (NOTES, "Government biases and the description").

