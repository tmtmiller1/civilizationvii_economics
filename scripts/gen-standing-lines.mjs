// gen-standing-lines.mjs - writes data/econ-standing-lines.sql: the marker buildings that carry Economics' standing
// Gold lines (docs/AI-NATIVE-LEVERS.md "Marker rules"), so the game and its AI count debt service and trade bills in
// Gold per turn. Each line is a ladder of ten rungs (1 to 512 Gold); the glue stands the rungs that sum to the line's
// whole Gold in the capital. Run after changing a line or a rung:
//   node scripts/gen-standing-lines.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
export const LINES = { DEBT: -1, LOAN: 1, BILL: -1, BILLIN: 1 };
export const RUNGS = [1, 2, 4, 8, 16, 32, 64, 128, 256, 512];

/** Every marker type with its signed Gold. */
export function markerTypes() {
  return Object.entries(LINES).flatMap(([line, sign]) => RUNGS.map((n) => ({ line, n,
    type: `BUILDING_ECON_LINE_${line}_${n}`, name: `LOC_ECONOMICS_LINE_${line}_${n}_NAME`, modifier: `ECON_LINE_${line}_${n}`, amount: sign * n })));
}

export function standingSql() {
  const rows = markerTypes();
  const values = rows.map((r) => `('${r.type}', '${r.line}', ${r.n}, '${r.modifier}', ${r.amount})`).join(",\n  ");
  return `-- Generated by scripts/gen-standing-lines.mjs; edit that, not this.
-- Economics' standing Gold lines (docs/AI-NATIVE-LEVERS.md "Marker rules", the owner's go 2026-11-04). Each marker is
-- a free City Center building the glue places in the capital: Population 0, ExistingDistrictOnly, CanBeHidden,
-- IGNORE_DISTRICT_PLACEMENT_CAP (no slot taken, nothing pushed out), AGELESS (no overbuild), TOWER_MARKER (every
-- Tower script that reads a city's buildings skips it), owned by a trait no civ has. The Gold rides a city modifier
-- the marker switches on, as the slot probe's CGOLD did: a yield on the building itself is scaled by the city's
-- Income percentage, the modifier charges exactly its Amount. Lines: DEBT and BILL take Gold, LOAN and BILLIN pay it.
INSERT OR IGNORE INTO Types (Type, Kind) VALUES ('TRAIT_ECON_LINE_NONE', 'KIND_TRAIT');
INSERT OR IGNORE INTO Traits (TraitType, InternalOnly) SELECT 'TRAIT_ECON_LINE_NONE', 1
WHERE EXISTS (SELECT 1 FROM Types WHERE Type = 'TRAIT_ECON_LINE_NONE');
CREATE TEMP TABLE econ_line_s (B TEXT, L TEXT, N INTEGER, M TEXT, A INTEGER);
INSERT INTO econ_line_s VALUES
  ${values};
INSERT OR IGNORE INTO Types (Type, Kind) SELECT B, 'KIND_CONSTRUCTIBLE' FROM econ_line_s;
INSERT OR IGNORE INTO Constructibles (ConstructibleType, Name, Description, Tooltip, ConstructibleClass, Cost,
  Population, ExistingDistrictOnly, CanBeHidden)
SELECT B, 'LOC_ECONOMICS_LINE_' || L || '_' || N || '_NAME', 'LOC_ECONOMICS_LINE_' || L || '_DESCRIPTION',
  'LOC_ECONOMICS_LINE_' || L || '_DESCRIPTION',
  'BUILDING', 1, 0, 1, 1
FROM econ_line_s WHERE B IN (SELECT Type FROM Types);
INSERT OR IGNORE INTO Buildings (ConstructibleType, Movable, Purchasable, Town, TraitType)
SELECT B, 0, 0, 1, 'TRAIT_ECON_LINE_NONE' FROM econ_line_s
WHERE B IN (SELECT ConstructibleType FROM Constructibles)
  AND EXISTS (SELECT 1 FROM Traits WHERE TraitType = 'TRAIT_ECON_LINE_NONE');
INSERT OR IGNORE INTO Constructible_ValidDistricts (ConstructibleType, DistrictType)
SELECT B, 'DISTRICT_CITY_CENTER' FROM econ_line_s
WHERE B IN (SELECT ConstructibleType FROM Constructibles)
  AND EXISTS (SELECT 1 FROM Districts WHERE DistrictType = 'DISTRICT_CITY_CENTER');
INSERT OR IGNORE INTO Tags (Tag, Category) VALUES ('TOWER_MARKER', 'CONSTRUCTIBLE_TAG');
INSERT OR IGNORE INTO TypeTags (Type, Tag)
SELECT B, T FROM econ_line_s, (SELECT 'IGNORE_DISTRICT_PLACEMENT_CAP' T UNION ALL SELECT 'TOWER_MARKER'
  UNION ALL SELECT 'AGELESS')
WHERE B IN (SELECT Type FROM Types) AND T IN (SELECT Tag FROM Tags);

-- One city modifier per rung: its Gold in the city that holds that rung's marker.
INSERT OR IGNORE INTO Types (Type, Kind) VALUES ('ECON_LINE_CITY_GOLD_TYPE', 'KIND_MODIFIER');
INSERT OR IGNORE INTO DynamicModifiers (ModifierType, CollectionType, EffectType)
SELECT 'ECON_LINE_CITY_GOLD_TYPE', 'COLLECTION_ALL_CITIES', 'EFFECT_CITY_ADJUST_YIELD'
WHERE EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'EFFECT_CITY_ADJUST_YIELD')
  AND EXISTS (SELECT 1 FROM Types WHERE Type = 'ECON_LINE_CITY_GOLD_TYPE');
INSERT OR IGNORE INTO Requirements (RequirementId, RequirementType)
SELECT 'REQ_' || M, 'REQUIREMENT_CITY_HAS_BUILDING' FROM econ_line_s WHERE B IN (SELECT ConstructibleType FROM Buildings);
INSERT OR IGNORE INTO RequirementArguments (RequirementId, Name, Value)
SELECT 'REQ_' || M, 'BuildingType', B FROM econ_line_s WHERE 'REQ_' || M IN (SELECT RequirementId FROM Requirements);
INSERT OR IGNORE INTO RequirementSets (RequirementSetId, RequirementSetType)
SELECT 'REQS_' || M, 'REQUIREMENTSET_TEST_ALL' FROM econ_line_s
WHERE 'REQ_' || M IN (SELECT RequirementId FROM Requirements);
INSERT OR IGNORE INTO RequirementSetRequirements (RequirementSetId, RequirementId)
SELECT 'REQS_' || M, 'REQ_' || M FROM econ_line_s WHERE 'REQS_' || M IN (SELECT RequirementSetId FROM RequirementSets);
INSERT OR IGNORE INTO Modifiers (ModifierId, ModifierType, SubjectRequirementSetId)
SELECT M, 'ECON_LINE_CITY_GOLD_TYPE', 'REQS_' || M FROM econ_line_s
WHERE 'REQS_' || M IN (SELECT RequirementSetId FROM RequirementSets)
  AND EXISTS (SELECT 1 FROM DynamicModifiers WHERE ModifierType = 'ECON_LINE_CITY_GOLD_TYPE');
INSERT OR IGNORE INTO ModifierArguments (ModifierId, Name, Value)
SELECT M, N, V FROM (
  SELECT M, 'YieldType' N, 'YIELD_GOLD' V FROM econ_line_s
  UNION ALL SELECT M, 'Amount', CAST(A AS TEXT) FROM econ_line_s
  UNION ALL SELECT M, 'Tooltip', 'LOC_ECONOMICS_LINE_' || L || '_' || N || '_NAME' FROM econ_line_s)
WHERE M IN (SELECT ModifierId FROM Modifiers);
INSERT OR IGNORE INTO GameModifiers (ModifierId) SELECT M FROM econ_line_s WHERE M IN (SELECT ModifierId FROM Modifiers);
DROP TABLE econ_line_s;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  fs.writeFileSync(path.join(root, "data/econ-standing-lines.sql"), standingSql());
}
