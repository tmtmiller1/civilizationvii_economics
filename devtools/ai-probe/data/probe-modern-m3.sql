-- M3: the Planned take as data: every city loses 20% of its Gold (no Tooltip, to see the default label) and gains
-- 20% of its Gold as Production (Tooltip LOC_ECONPROBE_PLANNED_NAME). Rows skip when a parent effect is missing.
INSERT OR IGNORE INTO Types (Type, Kind)
SELECT 'ECONPROBE_CITY_GOLD_CUT_TYPE', 'KIND_MODIFIER'
WHERE EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'EFFECT_CITY_ADJUST_YIELD');
INSERT OR IGNORE INTO Types (Type, Kind)
SELECT 'ECONPROBE_CITY_GOLD_TO_PROD_TYPE', 'KIND_MODIFIER'
WHERE EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'EFFECT_CITY_ADJUST_YIELD_CONVERSION');
INSERT OR IGNORE INTO DynamicModifiers (ModifierType, CollectionType, EffectType)
SELECT 'ECONPROBE_CITY_GOLD_CUT_TYPE', 'COLLECTION_ALL_CITIES', 'EFFECT_CITY_ADJUST_YIELD'
WHERE EXISTS (SELECT 1 FROM Types WHERE Type = 'ECONPROBE_CITY_GOLD_CUT_TYPE');
INSERT OR IGNORE INTO DynamicModifiers (ModifierType, CollectionType, EffectType)
SELECT 'ECONPROBE_CITY_GOLD_TO_PROD_TYPE', 'COLLECTION_ALL_CITIES', 'EFFECT_CITY_ADJUST_YIELD_CONVERSION'
WHERE EXISTS (SELECT 1 FROM Types WHERE Type = 'ECONPROBE_CITY_GOLD_TO_PROD_TYPE');
INSERT OR IGNORE INTO Modifiers (ModifierId, ModifierType)
SELECT 'ECONPROBE_M3_GOLD_CUT', 'ECONPROBE_CITY_GOLD_CUT_TYPE'
WHERE EXISTS (SELECT 1 FROM DynamicModifiers WHERE ModifierType = 'ECONPROBE_CITY_GOLD_CUT_TYPE');
INSERT OR IGNORE INTO Modifiers (ModifierId, ModifierType)
SELECT 'ECONPROBE_M3_GOLD_TO_PROD', 'ECONPROBE_CITY_GOLD_TO_PROD_TYPE'
WHERE EXISTS (SELECT 1 FROM DynamicModifiers WHERE ModifierType = 'ECONPROBE_CITY_GOLD_TO_PROD_TYPE');
INSERT OR IGNORE INTO ModifierArguments (ModifierId, Name, Value)
SELECT 'ECONPROBE_M3_GOLD_CUT', n, v FROM (SELECT 'YieldType' n, 'YIELD_GOLD' v UNION ALL SELECT 'Percent', '-20')
WHERE EXISTS (SELECT 1 FROM Modifiers WHERE ModifierId = 'ECONPROBE_M3_GOLD_CUT');
INSERT OR IGNORE INTO ModifierArguments (ModifierId, Name, Value)
SELECT 'ECONPROBE_M3_GOLD_TO_PROD', n, v FROM (SELECT 'FromYieldType' n, 'YIELD_GOLD' v UNION ALL
  SELECT 'ToYieldType', 'YIELD_PRODUCTION' UNION ALL SELECT 'Percent', '20' UNION ALL
  SELECT 'Tooltip', 'LOC_ECONPROBE_PLANNED_NAME')
WHERE EXISTS (SELECT 1 FROM Modifiers WHERE ModifierId = 'ECONPROBE_M3_GOLD_TO_PROD');
INSERT OR IGNORE INTO GameModifiers (ModifierId)
SELECT ModifierId FROM Modifiers WHERE ModifierId IN ('ECONPROBE_M3_GOLD_CUT', 'ECONPROBE_M3_GOLD_TO_PROD');
