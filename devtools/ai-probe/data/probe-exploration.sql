-- E1: EFFECT_ADJUST_MULTIPLY_TREASURY on the human seat, one guessed argument name per turn
-- (turn 3 Multiplier 2, turn 5 Percent 50, turn 7 Amount 3, turn 9 Factor 2).
-- E2: DIPLOMACY_ACTION_DEMAND_TRIBUTE granted to every major through EFFECT_DIPLOMACY_GRANT_DIPLOMATIC_ACTION.
-- E3: Hinder Finances re-pointed at the target's trade income (bottom of the file).
-- Every row is skipped when its parent effect, requirement or action is missing.

INSERT OR IGNORE INTO Types (Type, Kind)
SELECT 'ECONPROBE_MULTIPLY_TREASURY_TYPE', 'KIND_MODIFIER'
WHERE EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'EFFECT_ADJUST_MULTIPLY_TREASURY');
INSERT OR IGNORE INTO DynamicModifiers (ModifierType, CollectionType, EffectType)
SELECT 'ECONPROBE_MULTIPLY_TREASURY_TYPE', 'COLLECTION_ALL_PLAYERS', 'EFFECT_ADJUST_MULTIPLY_TREASURY'
WHERE EXISTS (SELECT 1 FROM Types WHERE Type = 'ECONPROBE_MULTIPLY_TREASURY_TYPE');

CREATE TEMP TABLE econprobe_e1 (Id TEXT, Turn INTEGER, ArgName TEXT, ArgValue TEXT);
INSERT INTO econprobe_e1 VALUES
  ('ECONPROBE_E1_MULTIPLIER', 3, 'Multiplier', '2'),
  ('ECONPROBE_E1_PERCENT',    5, 'Percent',    '50'),
  ('ECONPROBE_E1_AMOUNT',     7, 'Amount',     '3'),
  ('ECONPROBE_E1_FACTOR',     9, 'Factor',     '2');

INSERT OR IGNORE INTO Requirements (RequirementId, RequirementType)
SELECT 'ECONPROBE_REQ_HUMAN', 'REQUIREMENT_PLAYER_IS_HUMAN'
WHERE EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'REQUIREMENT_PLAYER_IS_HUMAN');
INSERT OR IGNORE INTO Requirements (RequirementId, RequirementType)
SELECT Id || '_REQ_TURN', 'REQUIREMENT_GAME_TURN_IS_X' FROM econprobe_e1
WHERE EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'REQUIREMENT_GAME_TURN_IS_X');
INSERT OR IGNORE INTO RequirementArguments (RequirementId, Name, Value)
SELECT Id || '_REQ_TURN', 'Turn', Turn FROM econprobe_e1
WHERE Id || '_REQ_TURN' IN (SELECT RequirementId FROM Requirements);
INSERT OR IGNORE INTO RequirementSets (RequirementSetId, RequirementSetType)
SELECT Id || '_REQS', 'REQUIREMENTSET_TEST_ALL' FROM econprobe_e1;
INSERT OR IGNORE INTO RequirementSetRequirements (RequirementSetId, RequirementId)
SELECT Id || '_REQS', 'ECONPROBE_REQ_HUMAN' FROM econprobe_e1
WHERE EXISTS (SELECT 1 FROM Requirements WHERE RequirementId = 'ECONPROBE_REQ_HUMAN');
INSERT OR IGNORE INTO RequirementSetRequirements (RequirementSetId, RequirementId)
SELECT Id || '_REQS', Id || '_REQ_TURN' FROM econprobe_e1
WHERE Id || '_REQ_TURN' IN (SELECT RequirementId FROM Requirements);

INSERT OR IGNORE INTO Modifiers (ModifierId, ModifierType, SubjectRequirementSetId)
SELECT Id, 'ECONPROBE_MULTIPLY_TREASURY_TYPE', Id || '_REQS' FROM econprobe_e1
WHERE EXISTS (SELECT 1 FROM DynamicModifiers WHERE ModifierType = 'ECONPROBE_MULTIPLY_TREASURY_TYPE');
INSERT OR IGNORE INTO ModifierArguments (ModifierId, Name, Value)
SELECT Id, ArgName, ArgValue FROM econprobe_e1 WHERE Id IN (SELECT ModifierId FROM Modifiers);
INSERT OR IGNORE INTO GameModifiers (ModifierId)
SELECT Id FROM econprobe_e1 WHERE Id IN (SELECT ModifierId FROM Modifiers);

