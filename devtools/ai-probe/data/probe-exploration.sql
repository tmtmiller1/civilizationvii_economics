-- E3: Hinder Finances (DIPLOMACY_ACTION_SABOTAGE_TREASURY) re-pointed: its completion now attaches to the target a
-- -50% cut to every city's trade-route yield (EFFECT_CITY_ADJUST_TRADE_YIELD) in place of the -10% Gold support.
INSERT OR IGNORE INTO Types (Type, Kind)
SELECT 'ECONPROBE_E3_ATTACH_TYPE', 'KIND_MODIFIER'
WHERE EXISTS (SELECT 1 FROM Modifiers WHERE ModifierId = 'PLAYER_DIPLOMACY_SABOTAGE_TREASURY_COMPLETE')
  AND EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'EFFECT_DAE_TARGET_ATTACH_MODIFIER');
INSERT OR IGNORE INTO Types (Type, Kind)
SELECT 'ECONPROBE_E3_TRADE_CUT_TYPE', 'KIND_MODIFIER'
WHERE EXISTS (SELECT 1 FROM Types WHERE Type = 'ECONPROBE_E3_ATTACH_TYPE')
  AND EXISTS (SELECT 1 FROM GameEffects WHERE Type = 'EFFECT_CITY_ADJUST_TRADE_YIELD');
INSERT OR IGNORE INTO DynamicModifiers (ModifierType, CollectionType, EffectType)
SELECT 'ECONPROBE_E3_ATTACH_TYPE', 'COLLECTION_OWNER', 'EFFECT_DAE_TARGET_ATTACH_MODIFIER'
WHERE EXISTS (SELECT 1 FROM Types WHERE Type = 'ECONPROBE_E3_TRADE_CUT_TYPE');
INSERT OR IGNORE INTO DynamicModifiers (ModifierType, CollectionType, EffectType)
SELECT 'ECONPROBE_E3_TRADE_CUT_TYPE', 'COLLECTION_PLAYER_CITIES', 'EFFECT_CITY_ADJUST_TRADE_YIELD'
WHERE EXISTS (SELECT 1 FROM Types WHERE Type = 'ECONPROBE_E3_TRADE_CUT_TYPE');
INSERT OR IGNORE INTO Modifiers (ModifierId, ModifierType)
SELECT 'ECONPROBE_E3_TRADE_CUT', 'ECONPROBE_E3_TRADE_CUT_TYPE'
WHERE EXISTS (SELECT 1 FROM DynamicModifiers WHERE ModifierType = 'ECONPROBE_E3_TRADE_CUT_TYPE');
INSERT OR IGNORE INTO ModifierArguments (ModifierId, Name, Value)
SELECT 'ECONPROBE_E3_TRADE_CUT', n, v FROM (SELECT 'Percent' n, '-50' v UNION ALL
  SELECT 'Tooltip', 'LOC_DIPLOMACY_PROJECT_SABOTAGE_TREASURY_NAME')
WHERE EXISTS (SELECT 1 FROM Modifiers WHERE ModifierId = 'ECONPROBE_E3_TRADE_CUT');
UPDATE Modifiers SET ModifierType = 'ECONPROBE_E3_ATTACH_TYPE'
WHERE ModifierId = 'PLAYER_DIPLOMACY_SABOTAGE_TREASURY_COMPLETE'
  AND EXISTS (SELECT 1 FROM Modifiers WHERE ModifierId = 'ECONPROBE_E3_TRADE_CUT')
  AND EXISTS (SELECT 1 FROM DynamicModifiers WHERE ModifierType = 'ECONPROBE_E3_ATTACH_TYPE');
INSERT OR REPLACE INTO ModifierArguments (ModifierId, Name, Value)
SELECT 'PLAYER_DIPLOMACY_SABOTAGE_TREASURY_COMPLETE', 'TargetPlayerAccept', 'ECONPROBE_E3_TRADE_CUT'
WHERE EXISTS (SELECT 1 FROM Modifiers WHERE ModifierId = 'PLAYER_DIPLOMACY_SABOTAGE_TREASURY_COMPLETE'
  AND ModifierType = 'ECONPROBE_E3_ATTACH_TYPE');
